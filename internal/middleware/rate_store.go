package middleware

import (
	"context"
	"time"
)

// RateStore — хранилище счетчиков для rate limiter: решает, укладывается ли еще один запрос
// по ключу key в лимит limit за окно window
//
// Интерфейс отделяет "как ограничиваем" (RateLimiter и HTTP-слой) от "где лежат счетчики"
// Две реализации дают одно и то же поведение в разных условиях: MemoryRateStore — для локальной
// разработки и одного инстанса, RedisRateStore — для нескольких инстансов с общим счетчиком
//
// ctx нужен сетевым реализациям: запрос к Redis должен отменяться вместе с HTTP-запросом,
// а не висеть сам по себе, in-memory реализации контекст не нужен, но сигнатура одна на всех
//
// key — строка, а не int64 userID: хранилище не знает, что именно ограничивается
// (пользователь, IP, эндпоинт) — это решает вызывающий код
//
// limit и window передаются аргументами, а не хранятся в полях структуры: Redis-реализации
// окно нужно в момент создания ключа (как его TTL), а не в момент создания клиента,
// и хранилище остается простым исполнителем без собственных настроек лимита
//
// Ошибка зарезервирована под сетевые реализации: MemoryRateStore всегда возвращает nil,
// а Redis может быть недоступен
// Вызывающий код обязан ее обработать, значение bool при ошибке смысла не имеет
type RateStore interface {
	Allow(ctx context.Context, key string, limit int, window time.Duration) (bool, error)
}
